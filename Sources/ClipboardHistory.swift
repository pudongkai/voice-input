import Cocoa

/// 剪贴板历史中的一条记录，只保存在内存里。
struct ClipboardEntry: Identifiable {
    enum Content {
        case text(String)
        /// 图片统一存成 PNG，比剪贴板里常见的 TIFF 小得多。
        case image(png: Data, thumbnail: NSImage, pixelSize: NSSize)

        func isSame(as other: Content) -> Bool {
            switch (self, other) {
            case let (.text(a), .text(b)): return a == b
            case let (.image(a, _, _), .image(b, _, _)): return a == b
            default: return false
            }
        }
    }

    let id = UUID()
    let content: Content
    let copiedAt: Date
}

/// 记录最近复制过的文字和图片。
/// macOS 没有剪贴板变化的通知，只能定时比较 changeCount。
final class ClipboardHistory: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []

    var capacity: Int {
        didSet { trim() }
    }

    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var timer: Timer?

    /// 密码管理器等用这些类型标记不该被记录的内容（nspasteboard.org 的约定）。
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(capacity: Int, pasteboard: NSPasteboard = .general) {
        self.capacity = capacity
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func clear() {
        entries.removeAll()
    }

    func entry(id: UUID) -> ClipboardEntry? {
        entries.first { $0.id == id }
    }

    /// 把一条记录写回剪贴板，并移到最前面。
    func restore(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        switch entry.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image(let png, _, _):
            // 同时提供 TIFF，兼容只认 TIFF 的老应用。
            pasteboard.setData(png, forType: .png)
            if let tiff = NSImage(data: png)?.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        }
        lastChangeCount = pasteboard.changeCount
        insert(entry.content)
    }

    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if let content = readContent() {
            insert(content)
        }
    }

    private func readContent() -> ClipboardEntry.Content? {
        let types = pasteboard.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return nil }
        // Finder 复制文件时也会附带图标图片，文件不在记录范围内。
        if types.contains(.fileURL) { return nil }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text)
        }
        return readImage()
    }

    private func readImage() -> ClipboardEntry.Content? {
        let raw = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff)
        guard let raw, let rep = NSBitmapImageRep(data: raw) else { return nil }
        let png = pasteboard.data(forType: .png) ?? rep.representation(using: .png, properties: [:])
        guard let png else { return nil }
        let pixelSize = NSSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        return .image(png: png, thumbnail: Self.thumbnail(of: rep), pixelSize: pixelSize)
    }

    private func insert(_ content: ClipboardEntry.Content) {
        entries.removeAll { $0.content.isSame(as: content) }
        entries.insert(ClipboardEntry(content: content, copiedAt: Date()), at: 0)
        trim()
    }

    private func trim() {
        if entries.count > capacity {
            entries.removeLast(entries.count - capacity)
        }
    }

    /// 列表里只显示小图，提前缩小可以避免每次重绘都处理原图。
    private static func thumbnail(of rep: NSBitmapImageRep, maxSide: CGFloat = 120) -> NSImage {
        let width = CGFloat(rep.pixelsWide), height = CGFloat(rep.pixelsHigh)
        let scale = min(1, maxSide / max(width, height, 1))
        let size = NSSize(width: max(1, width * scale), height: max(1, height * scale))
        let image = NSImage(size: size)
        image.lockFocus()
        NSGraphicsContext.current?.imageInterpolation = .high
        rep.draw(in: NSRect(origin: .zero, size: size))
        image.unlockFocus()
        return image
    }
}
